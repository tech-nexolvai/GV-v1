def _schemas(engine: Engine, like: str) -> list[str]:
    with engine.connect() as connection:
        return [
            row[0]
            for row in connection.execute(
                text(
                    "SELECT schema_name FROM information_schema.schemata WHERE schema_name LIKE :p"
                ),
                {"p": like},
            )
        ]


def _public_tables(engine: Engine) -> int:
    with engine.connect() as connection:
        count = connection.execute(
            text("SELECT count(*) FROM pg_tables WHERE schemaname = 'public'")
        ).scalar_one()
    return int(count)


def _tables_in(engine: Engine, schema: str) -> int:
    with engine.connect() as connection:
        count = connection.execute(
            text("SELECT count(*) FROM pg_tables WHERE schemaname = :s"), {"s": schema}
        ).scalar_one()
    return int(count)


@contextmanager
def _sandbox(engine: Engine) -> Iterator[tuple[str, str]]:
    """An empty schema on the grader's search path, and the URL pointing at it.

    **Why not just hand the grader `postgres_engine`'s own URL.** That URL already pins
    `search_path=gv_test_<hash>,public`, so a grader that skipped making a schema of its own would
    still land inside the test's schema and `public` would stay empty — the assertion would pass
    and the regression would be invisible. Verified by mutation: reverting the fix left this file's
    `public` count unchanged.

    So the test supplies a schema it knows starts empty, and asserts the grader put *nothing* in it.
    A grader that migrates into whatever it was given fills it; one that makes its own leaves it
    untouched. `public` is never written either way, which is what keeps this test from being the
    thing it warns about.
    """
    schema = f"gv_sandbox_{uuid4().hex}"
    admin = create_engine(engine.url, isolation_level="AUTOCOMMIT")
    try:
        with admin.connect() as connection:
            connection.execute(text(f'CREATE SCHEMA "{schema}"'))
        scoped = engine.url.update_query_dict(
            {"options": f"-csearch_path={schema},public"}
        ).render_as_string(hide_password=False)
        try:
            yield scoped, schema
        finally:
            with admin.connect() as connection:
                connection.execute(text(f'DROP SCHEMA "{schema}" CASCADE'))
    finally:
        admin.dispose()


def test_the_private_schema_is_created_and_then_dropped(postgres_engine: Engine) -> None:
    """Input: the context manager. Outcome: a schema exists inside it and is gone after."""
    url = postgres_engine.url.render_as_string(hide_password=False)

    with _private_schema(url) as scoped:
        inside = _schemas(postgres_engine, "gv_eval_%")
        assert len(inside) == 1
        assert inside[0] in scoped, "the yielded URL should put the new schema on the search path"
        assert "public" in scoped, "public stays on the path so the extensions resolve"

    assert _schemas(postgres_engine, "gv_eval_%") == []


def test_the_private_schema_is_dropped_even_when_the_run_fails(postgres_engine: Engine) -> None:
    """**Input: an exception inside the block. Outcome: nothing left behind.**

    An interrupted grading run is ordinary — a bad answer key, a reader that raises. If the schema
    survived it, the leftovers would accumulate silently in whatever database somebody happened to
    point the tool at.
    """
    url = postgres_engine.url.render_as_string(hide_password=False)

    with pytest.raises(RuntimeError), _private_schema(url):
        assert _schemas(postgres_engine, "gv_eval_%")
        raise RuntimeError("the reader fell over")

    assert _schemas(postgres_engine, "gv_eval_%") == []


def test_the_grader_leaves_the_database_exactly_as_it_found_it(
    postgres_engine: Engine, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """**The regression.** Input: a full run. Outcome: it wrote into no schema it was handed.

    The first version migrated into whatever `DATABASE_URL` named, which put every table into
    `public` on the shared test database — and every per-test schema sees `public` through its
    `search_path`, so the suite's next run finds rows and tables it never created. It presents as
    `assert 7 == 2`, `MultipleResultsFound`, or fifty failures that look like a regression in the
    last thing you wrote, and it has cost this project two separate debugging detours.

    The grader is given an empty schema and must leave it empty, having made and dropped one of its
    own. See `_sandbox` for why handing it the test's own URL would not have caught this.
    """
    directory = make_fixture(tmp_path / "package")
    public_before = _public_tables(postgres_engine)

    with _sandbox(postgres_engine) as (scoped_url, sandbox):
        assert _tables_in(postgres_engine, sandbox) == 0, "the sandbox should start empty"

        exit_code = main_with(evaluation_args(scoped_url, directory))

        assert exit_code == 0, "no critical false PASS on the synthetic package"
        assert (
            _tables_in(postgres_engine, sandbox) == 0
        ), "the grader migrated into the schema it was handed instead of making its own"

    assert _public_tables(postgres_engine) == public_before, "the grader wrote into public"
    assert _schemas(postgres_engine, "gv_eval_%") == [], "the grader left its schema behind"
    assert "Answer-key scorecard" in capsys.readouterr().out


