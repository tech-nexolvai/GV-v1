def test_a_wrong_reading_is_reported_as_wrong(
    postgres_engine: Engine, tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """**Input: the synthetic package. Outcome: one reading right, one reported wrong.**

    The fixture's second dimension is `28 3/4"` — a mixed fraction with a space in it, which
    `extract_words` splits, so the reader confirms `3/4"`. That is a genuine weakness in the reader
    and the grader has to show it.

    Asserted because the alternative is a tautology. The answer key supplies the reviewer's *types*
    so a rule can run at all, and if it supplied the *values* too then reading accuracy would be
    100% by construction and the number would mean nothing. This is what proves it does not.
    """
    directory = make_fixture(tmp_path / "package")
    url = postgres_engine.url.render_as_string(hide_password=False)

    main_with(evaluation_args(url, directory))

    printed = capsys.readouterr().out
    assert "reading accuracy      50.0%" in printed
    assert "reading coverage      100.0%" in printed, "both answers were attempted"
    assert "XX " in printed, "the misread dimension should be marked, not hidden"


