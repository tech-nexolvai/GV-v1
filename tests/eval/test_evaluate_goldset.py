def test_a_drawing_that_changed_under_its_answers_is_refused(tmp_path: Path) -> None:
    """**Input: the same key, one byte of the drawing different. Outcome: refused.**

    An annotation is a statement about specific bytes. Scored against different bytes it is not
    missing or noisy — it is *confidently wrong*, and it reads as a passing gate. This is the same
    check `eval/gold_set/store.py` makes, asserted here because the grader is the thing that would
    otherwise run on a stale case without anybody noticing.
    """
    directory = make_fixture(tmp_path / "package")
    case = load_package(directory)
    shop = directory / case.shop
    shop.write_bytes(shop.read_bytes() + b"\n% a later revision\n")

    with pytest.raises(ManifestLoadError) as refused:
        load_package(directory)

    assert "hash" in str(refused.value).lower() or "changed" in str(refused.value).lower()


