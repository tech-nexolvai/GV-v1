def _reviewed_overlay_with_visible_vendor_reading() -> bytes:
    """A synthetic reviewed sheet: vendor value in a stamp, different answer in FreeText."""
    from tests.extraction.test_annotations import _free_text, _pdf, _stamp

    stream = b"1 w 100 500 m 300 500 l S\n" b'BT /F1 48 Tf 120 560 Td (25.5\\") Tj ET\n'
    compressed = zlib.compress(stream)
    appearance = (
        b"<< /Type /XObject /Subtype /Form /FormType 1 /BBox [100 500 400 700] "
        b"/Matrix [1 0 0 1 -100 -500] /Resources << /Font << /F1 8 0 R >> >> "
        b"/Filter /FlateDecode /Length "
        + str(len(compressed)).encode()
        + b" >>\nstream\n"
        + compressed
        + b"\nendstream"
    )
    font = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"
    return _pdf(
        annotations=[_free_text('99"'), _stamp(appearance_object=7)],
        extra_objects=[appearance, font],
    )


def test_the_extraction_stage_never_receives_the_reviewer_answer(
    postgres_engine: Engine, tmp_path: Path
) -> None:
    """The full grader path reads the stamp's value and cannot emit the FreeText answer."""
    from app.models.evidence import ObservationCandidate
    from eval.gold_set.store import content_hash

    directory = tmp_path / "reviewed-package"
    directory.mkdir()
    reviewed = _reviewed_overlay_with_visible_vendor_reading()
    (directory / "shop.pdf").write_bytes(reviewed)
    (directory / "arch.pdf").write_bytes(reviewed)
    key = {
        "id": "synthetic-reviewed-layer-boundary",
        "product_type": "countertop",
        "arch": "arch.pdf",
        "shop": "shop.pdf",
        "ground_truth": {"observations": [], "matches": [], "expected_findings": []},
        "provenance": {
            "annotator": "synthetic-fixture",
            "annotated_on": "2026-09-09",
            "documents": [
                {
                    "source": "SHOP",
                    "document_version_id": str(uuid4()),
                    "content_hash": content_hash(directory / "shop.pdf"),
                }
            ],
        },
    }
    (directory / ANSWER_KEY).write_text(json.dumps(key), encoding="utf-8")
    case = load_package(directory)
    association = AssociationSettings(
        line_minimum_pt=Decimal(50),
        glyph_maximum_pt=Decimal(10),
        glyph_gap_pt=Decimal(4),
        proximity_limit=Decimal("0.3"),
        ambiguity_margin=Decimal("0.01"),
    )
    url = postgres_engine.url.render_as_string(hide_password=False)

    with _private_schema(url) as scoped_url:
        result = _run_pipeline(
            case,
            directory,
            scoped_url,
            dpi=150,
            association=association,
            vendor_stamps_only=True,
        )
        candidates = list(result.session.scalars(select(ObservationCandidate)))
        result.session.close()

    assert result.stripped_annotations == 1
    assert any("25.5" in candidate.raw_text for candidate in candidates)
    assert all("99" not in candidate.raw_text for candidate in candidates)
    assert all(candidate.source_author is None for candidate in candidates)


