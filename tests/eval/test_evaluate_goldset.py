def main_with(argv: list[str]) -> int:
    """Run `main()` with an argument list, the way the command line would.

    `main` reads `sys.argv` through `argparse`, so a test that called it directly would be testing a
    different entry point from the one a person uses — including the argument parsing, which is
    where the `--database-url` default lives.
    """
    import sys

    original = sys.argv
    sys.argv = ["evaluate_goldset.py", *argv]
    try:
        return main()
    finally:
        sys.argv = original


def evaluation_args(database_url: str, directory: Path) -> list[str]:
    """The generated fixture's explicit association configuration."""
    return ["--database-url", database_url, *ASSOCIATION_ARGUMENTS, str(directory)]


