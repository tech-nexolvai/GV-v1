"""The package-lane grader: what it generates, what it refuses, and what it leaves behind (#553).

Verification for: `scripts/evaluate_goldset.py`.

**The one to read first is `test_the_grader_leaves_the_database_exactly_as_it_found_it`.** The first
version of the script migrated straight into whatever `DATABASE_URL` named, which put every table
into `public` on the shared test database — and since each test schema has `public` on its
`search_path`, the next run of the suite starts finding rows it never created. That failure does not
look like a polluted database; it looks like a regression in whatever you wrote last, and it has cost
this project two separate debugging detours. The script's own `--help` said "its own schema" while it
did no such thing.

The second is `test_a_wrong_reading_is_reported_as_wrong`. A grader whose fixture it always scores
100% on proves only that it can say yes. The synthetic package deliberately contains one dimension
the reader gets wrong, so this file asserts the grader can report a failure — which is the only
version of it worth running.

Everything here is generated by `--make-fixture`. No client drawing, and no number tuned against one.
"""

